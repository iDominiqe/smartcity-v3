export class I18nManager {
  constructor(initialLang = 'en') {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('neo_v3_lang') : null;
    const chosen = saved && TRANSLATIONS[saved] ? saved : initialLang;
    this.lang = TRANSLATIONS[chosen] ? chosen : 'en';
    this.listeners = [];
  }

  get dict() {
    return TRANSLATIONS[this.lang] || TRANSLATIONS.en;
  }

  t(key) {
    return this.dict[key] ?? TRANSLATIONS.en[key] ?? key;
  }

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.lang = lang;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('neo_v3_lang', lang);
    }
    document.documentElement.lang = lang;
    this.applyToDOM();
    this.listeners.forEach((fn) => fn(lang));
  }

  onChange(fn) {
    this.listeners.push(fn);
  }

  applyToDOM() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val && typeof val === 'string') {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val && typeof val === 'string') {
        el.setAttribute('placeholder', val);
      }
    });
  }
}
